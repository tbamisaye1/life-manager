const RECENT_KEY = 'lm-recent-emojis'
const MAX_RECENT = 24

export function getRecentEmojis() {
  try {
    const raw = localStorage.getItem(RECENT_KEY)
    return raw ? JSON.parse(raw) : []
  } catch {
    return []
  }
}

export function addRecentEmoji(emoji) {
  if (!emoji) return
  const recent = getRecentEmojis().filter((e) => e !== emoji)
  recent.unshift(emoji)
  localStorage.setItem(RECENT_KEY, JSON.stringify(recent.slice(0, MAX_RECENT)))
}

export function searchEmojis(query) {
  const q = query.trim().toLowerCase()
  if (!q) return null
  const all = EMOJI_CATEGORIES.flatMap((c) => c.emojis)
  const unique = [...new Set(all)]
  return unique.filter((e) => e.includes(q) || cLabelFor(e)?.toLowerCase().includes(q))
}

function cLabelFor(emoji) {
  for (const c of EMOJI_CATEGORIES) {
    if (c.emojis.includes(emoji)) return c.label
  }
  return ''
}

export function randomEmoji() {
  const all = EMOJI_CATEGORIES.flatMap((c) => c.emojis)
  return all[Math.floor(Math.random() * all.length)]
}

export function categoriesWithRecent() {
  const recent = getRecentEmojis()
  if (recent.length === 0) return EMOJI_CATEGORIES
  return [{ id: 'recent', label: 'Recent', icon: '🕐', emojis: recent }, ...EMOJI_CATEGORIES]
}
